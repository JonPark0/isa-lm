"""Writes model/unicode_tables.c: code point ranges of the Unicode letter (L*)
and number (N*) categories, for the Llama 3 pre-tokenizer in model/bpe.c, and
the canonical decomposition, combining class and composition tables for NFC
(model/unicode.c). Hangul syllables are algorithmic and not in the tables.

    python3 tools/gen_unicode.py > model/unicode_tables.c

The tables follow this Python's unicodedata version (printed in the header).
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    print(f"const uint32_t {name}[][2] = {{")
    for i in range(0, len(rs), 4):
        print("    " + " ".join(f"{{ 0x{a:X}, 0x{b:X} }}," for a, b in rs[i:i + 4]))
    print("};")
    print(f"const int {name}_n = {len(rs)};\n")


HANGUL = range(0xAC00, 0xD7A4)


def canonical(c):
    """One level of canonical decomposition, or None."""
    d = unicodedata.decomposition(chr(c))
    return None if not d or d.startswith("<") else [int(x, 16) for x in d.split()]


def full_decomposition(c):
    d = canonical(c)
    return [c] if d is None else [x for y in d for x in full_decomposition(y)]


def emit_nfc():
    cps = [c for c in range(0x110000) if c not in HANGUL and canonical(c)]
    pool, rows = [], []
    for c in cps:
        d = full_decomposition(c)
        rows.append(f"{{ 0x{c:X}, {len(pool)}, {len(d)} }}")
        pool += d
    print(f"const uint32_t ml_uni_decomp_pool[] = {{")
    for i in range(0, len(pool), 8):
        print("    " + " ".join(f"0x{x:X}," for x in pool[i:i + 8]))
    print("};\n")
    print("const ml_uni_decomp ml_uni_decomp_tab[] = {")
    for i in range(0, len(rows), 4):
        print("    " + " ".join(r + "," for r in rows[i:i + 4]))
    print("};")
    print(f"const int ml_uni_decomp_n = {len(rows)};\n")

    ccc = []   # runs of equal non-zero combining class
    for c in range(0x110000):
        v = unicodedata.combining(chr(c))
        if v and ccc and ccc[-1][1] == c - 1 and ccc[-1][2] == v:
            ccc[-1][1] = c
        elif v:
            ccc.append([c, c, v])
    print("const ml_uni_ccc ml_uni_ccc_tab[] = {")
    for i in range(0, len(ccc), 4):
        print("    " + " ".join(f"{{ 0x{a:X}, 0x{b:X}, {v} }}," for a, b, v in ccc[i:i + 4]))
    print("};")
    print(f"const int ml_uni_ccc_n = {len(ccc)};\n")

    # primary composites: two-code-point decompositions that NFC recomposes.
    # The Hugging Face tokenizers library (Rust unicode-normalization) does not
    # compose U+11935 U+11930 -> U+11938; follow it so that ids match.
    comp = sorted((canonical(c)[0], canonical(c)[1], c) for c in cps if len(canonical(c)) == 2
                  and unicodedata.normalize("NFC", unicodedata.normalize("NFD", chr(c))) == chr(c)
                  and c != 0x11938)
    print("const ml_uni_comp ml_uni_comp_tab[] = {")
    for i in range(0, len(comp), 3):
        print("    " + " ".join(f"{{ 0x{a:X}, 0x{b:X}, 0x{c:X} }}," for a, b, c in comp[i:i + 3]))
    print("};")
    print(f"const int ml_uni_comp_n = {len(comp)};")


def main():
    cat = lambda c: unicodedata.category(chr(c))
    print(f"/* Generated by tools/gen_unicode.py from Unicode {unicodedata.unidata_version}. Do not edit. */")
    print('#include "model/unicode.h"\n')
    emit("ml_uni_letter", ranges(lambda c: cat(c)[0] == "L"))
    emit("ml_uni_number", ranges(lambda c: cat(c)[0] == "N"))
    emit_nfc()


if __name__ == "__main__":
    sys.exit(main())
